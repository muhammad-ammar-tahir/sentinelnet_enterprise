"""SQLAlchemy ORM Data Models for SentinelNet.

Defines schemas for devices, links, incidents, telemetry metrics,
recovery actions, operational policies, administrative users, and audit logs.
Includes composite indexes for high-throughput time-series queries.
"""

from datetime import datetime, timezone
from typing import Optional, List, Dict, Any
import logging
from sqlalchemy import (
    Column,
    String,
    Integer,
    Float,
    Boolean,
    DateTime,
    ForeignKey,
    Text,
    JSON,
    Index,
)
from sqlalchemy.orm import relationship, Mapped, mapped_column
from backend.database.database import Base

logger = logging.getLogger(__name__)


class Device(Base):
    """Network Device model (OpenFlow switch, host, router, or gateway)."""
    __tablename__ = "devices"

    id: Mapped[str] = mapped_column(String(64), primary_key=True, index=True)
    name: Mapped[str] = mapped_column(String(128), nullable=False)
    device_type: Mapped[str] = mapped_column(String(32), nullable=False)  # switch, host, server, router, controller
    ip_address: Mapped[Optional[str]] = mapped_column(String(45), nullable=True)
    mac_address: Mapped[Optional[str]] = mapped_column(String(17), nullable=True)
    dpid: Mapped[Optional[str]] = mapped_column(String(32), nullable=True, index=True)  # OpenFlow DPID
    status: Mapped[str] = mapped_column(String(20), default="active", nullable=False)  # active, degraded, down
    location: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow)
    updated_at: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    # Relationships
    source_links: Mapped[List["Link"]] = relationship("Link", foreign_keys="Link.src_device_id", back_populates="src_device")
    target_links: Mapped[List["Link"]] = relationship("Link", foreign_keys="Link.dst_device_id", back_populates="dst_device")
    metrics: Mapped[List["NetworkMetric"]] = relationship("NetworkMetric", back_populates="device")


class Link(Base):
    """Network Link connecting two devices/ports."""
    __tablename__ = "links"

    id: Mapped[str] = mapped_column(String(64), primary_key=True, index=True)
    src_device_id: Mapped[str] = mapped_column(String(64), ForeignKey("devices.id"), nullable=False)
    dst_device_id: Mapped[str] = mapped_column(String(64), ForeignKey("devices.id"), nullable=False)
    src_port: Mapped[int] = mapped_column(Integer, nullable=False)
    dst_port: Mapped[int] = mapped_column(Integer, nullable=False)
    link_type: Mapped[str] = mapped_column(String(20), default="primary")  # primary, backup, access
    status: Mapped[str] = mapped_column(String(20), default="up")  # up, down, congested, degraded
    bandwidth_mbps: Mapped[float] = mapped_column(Float, default=100.0)
    capacity_mbps: Mapped[Optional[float]] = mapped_column(Float, nullable=True, default=100.0)
    current_utilization: Mapped[float] = mapped_column(Float, default=0.0)
    latency_ms: Mapped[float] = mapped_column(Float, default=1.0)
    packet_loss_rate: Mapped[float] = mapped_column(Float, default=0.0)

    # Relationships
    src_device: Mapped["Device"] = relationship("Device", foreign_keys=[src_device_id], back_populates="source_links")
    dst_device: Mapped["Device"] = relationship("Device", foreign_keys=[dst_device_id], back_populates="target_links")


class Incident(Base):
    """Network Incident Record generated by Detection or Diagnostics."""
    __tablename__ = "incidents"

    id: Mapped[str] = mapped_column(String(64), primary_key=True, index=True)
    title: Mapped[str] = mapped_column(String(255), nullable=False)
    severity: Mapped[str] = mapped_column(String(20), nullable=False)  # critical, major, minor, warning
    status: Mapped[str] = mapped_column(String(30), default="detected")  # detected, diagnosing, mitigating, resolved, failed
    affected_device_id: Mapped[Optional[str]] = mapped_column(String(64), ForeignKey("devices.id"), nullable=True)
    affected_link_id: Mapped[Optional[str]] = mapped_column(String(64), ForeignKey("links.id"), nullable=True)
    root_cause: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    confidence_score: Mapped[float] = mapped_column(Float, default=0.0)
    detected_at: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow)
    resolved_at: Mapped[Optional[datetime]] = mapped_column(DateTime, nullable=True)
    metadata_payload: Mapped[Optional[Dict[str, Any]]] = mapped_column(JSON, nullable=True)

    # Relationships
    recovery_actions: Mapped[List["RecoveryAction"]] = relationship("RecoveryAction", back_populates="incident")

    # Indexes
    __table_args__ = (
        Index("ix_incidents_status", "status"),
        Index("ix_incidents_severity", "severity"),
        Index("ix_incidents_detected_at_desc", detected_at.desc()),
    )

    def to_dict(self) -> Dict[str, Any]:
        """Convert Incident to serializable dictionary."""
        meta = self.metadata_payload or {}
        entity = self.affected_link_id or self.affected_device_id or meta.get("target_id") or "unknown"
        return {
            "id": self.id,
            "incident_id": self.id,
            "title": self.title,
            "severity": self.severity,
            "status": self.status,
            "affected_device_id": self.affected_device_id,
            "affected_link_id": self.affected_link_id,
            "affected_entity": entity,
            "target_device": entity,
            "root_cause": self.root_cause,
            "fault_type": self.root_cause,                                 # alias used by e2e test
            "confidence": round(self.confidence_score or 0.0, 2),
            "confidence_score": self.confidence_score,
            "detected_at": self.detected_at.isoformat() if self.detected_at else None,
            "resolved_at": self.resolved_at.isoformat() if self.resolved_at else None,
            # Expose recovery_action_id from metadata so API consumers don't
            # need a separate join — stamped by RecoveryEngine on success.
            "recovery_action_id": meta.get("recovery_action_id"),
            "metadata_payload": meta,
            "telemetry_snapshot": meta.get("affected_metrics", meta.get("snapshot", {})),
        }

    def dict(self) -> Dict[str, Any]:
        """Alias for Pydantic-like serialization compatibility."""
        return self.to_dict()


class RecoveryAction(Base):
    """Executed or Planned Self-Healing Recovery Action."""
    __tablename__ = "recovery_actions"

    id: Mapped[str] = mapped_column(String(64), primary_key=True, index=True)
    incident_id: Mapped[str] = mapped_column(String(64), ForeignKey("incidents.id"), nullable=False)
    action_type: Mapped[str] = mapped_column(String(64), nullable=False)  # flow_reroute, rate_limit, link_failover, port_restart
    status: Mapped[str] = mapped_column(String(30), default="pending")  # pending, executing, success, failed, rolled_back
    target_dpid: Mapped[Optional[str]] = mapped_column(String(32), nullable=True)
    parameters: Mapped[Optional[Dict[str, Any]]] = mapped_column(JSON, nullable=True)
    execution_duration_ms: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    rollback_status: Mapped[Optional[str]] = mapped_column(String(30), nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow)
    executed_at: Mapped[Optional[datetime]] = mapped_column(DateTime, nullable=True)

    # Relationships
    incident: Mapped["Incident"] = relationship("Incident", back_populates="recovery_actions")

    # Indexes
    __table_args__ = (
        Index("ix_recovery_actions_incident_id", "incident_id"),
        Index("ix_recovery_actions_executed_at", "executed_at"),
    )

    @property
    def snapshot_id(self) -> Optional[str]:
        """Extract snapshot ID from parameters payload."""
        if self.parameters and isinstance(self.parameters, dict):
            return self.parameters.get("snapshot_id")
        return None

    @snapshot_id.setter
    def snapshot_id(self, val: Optional[str]) -> None:
        params = dict(self.parameters or {})
        params["snapshot_id"] = val
        self.parameters = params

    @property
    def result(self) -> str:
        """Alias for status."""
        return self.status

    @result.setter
    def result(self, val: str) -> None:
        self.status = val

    @property
    def rolled_back_at(self) -> Optional[datetime]:
        """Extract rollback timestamp from parameters."""
        if self.parameters and isinstance(self.parameters, dict):
            ts = self.parameters.get("rolled_back_at")
            if ts:
                try:
                    return datetime.fromisoformat(ts)
                except Exception:
                    pass
        return None

    @rolled_back_at.setter
    def rolled_back_at(self, val: Any) -> None:
        params = dict(self.parameters or {})
        params["rolled_back_at"] = val.isoformat() if isinstance(val, datetime) else str(val)
        self.parameters = params

    @property
    def rolled_back_by(self) -> Optional[str]:
        """Extract operator identifier who initiated rollback."""
        if self.parameters and isinstance(self.parameters, dict):
            return self.parameters.get("rolled_back_by")
        return None

    @rolled_back_by.setter
    def rolled_back_by(self, val: Any) -> None:
        params = dict(self.parameters or {})
        params["rolled_back_by"] = str(val)
        self.parameters = params

    def to_dict(self) -> Dict[str, Any]:
        """Convert RecoveryAction to dictionary representation."""
        return {
            "id": self.id,
            "incident_id": self.incident_id,
            "action_type": self.action_type,
            "status": self.status,
            "result": self.result,
            "target_dpid": self.target_dpid,
            "snapshot_id": self.snapshot_id,
            "parameters": self.parameters or {},
            "execution_duration_ms": self.execution_duration_ms,
            "rollback_status": self.rollback_status,
            "rolled_back_at": self.rolled_back_at.isoformat() if self.rolled_back_at else None,
            "rolled_back_by": self.rolled_back_by,
            "created_at": self.created_at.isoformat() if self.created_at else None,
            "executed_at": self.executed_at.isoformat() if self.executed_at else None,
        }

    def dict(self) -> Dict[str, Any]:
        return self.to_dict()


class NetworkMetric(Base):
    """Time-series Network Telemetry Point with honest nullability and measurement tracking."""
    __tablename__ = "metrics"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    device_id: Mapped[Optional[str]] = mapped_column(String(64), ForeignKey("devices.id"), nullable=True)
    metric_name: Mapped[str] = mapped_column(String(64), nullable=False, index=True)
    metric_value: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    capacity_mbps: Mapped[Optional[float]] = mapped_column(Float, nullable=True)  # for links only
    utilization_pct: Mapped[Optional[float]] = mapped_column(Float, nullable=True)  # computed
    measurement_method: Mapped[Optional[str]] = mapped_column(String(32), nullable=True)  # icmp, tcp, ovs_counter, snmp, unavailable
    missing_fields: Mapped[Optional[List[str]]] = mapped_column(JSON, nullable=True)
    timestamp: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow, index=True)
    labels: Mapped[Optional[Dict[str, Any]]] = mapped_column(JSON, nullable=True)

    # Relationships
    device: Mapped[Optional["Device"]] = relationship("Device", back_populates="metrics")

    # Indexes
    __table_args__ = (
        Index("ix_metrics_device_id_timestamp_desc", "device_id", timestamp.desc()),
        Index("ix_metrics_timestamp_idx", "timestamp"),
    )


class Policy(Base):
    """Self-healing policy rule."""
    __tablename__ = "policies"

    id: Mapped[str] = mapped_column(String(64), primary_key=True, index=True)
    name: Mapped[str] = mapped_column(String(128), nullable=False)
    rule_condition: Mapped[str] = mapped_column(String(255), nullable=False)
    action_template: Mapped[str] = mapped_column(String(64), nullable=False)
    is_active: Mapped[bool] = mapped_column(Boolean, default=True)
    priority: Mapped[int] = mapped_column(Integer, default=100)


class User(Base):
    """User account for SentinelNet RBAC."""
    __tablename__ = "users"

    id: Mapped[str] = mapped_column(String(64), primary_key=True, index=True)
    username: Mapped[str] = mapped_column(String(64), unique=True, index=True, nullable=False)
    email: Mapped[str] = mapped_column(String(128), unique=True, index=True, nullable=False)
    hashed_password: Mapped[str] = mapped_column(String(255), nullable=False)
    role: Mapped[str] = mapped_column(String(32), default="operator")  # admin, operator, viewer
    is_active: Mapped[bool] = mapped_column(Boolean, default=True)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow)


class AuditLog(Base):
    """System-wide operational and security audit log."""
    __tablename__ = "audit_logs"

    id: Mapped[str] = mapped_column(String(64), primary_key=True, index=True)
    action: Mapped[str] = mapped_column(String(64), nullable=False)
    actor: Mapped[str] = mapped_column(String(64), nullable=False, default="system")
    details: Mapped[Optional[Dict[str, Any]]] = mapped_column(JSON, nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow, index=True)
