"""backend/recovery/action_executor.py — Execution of SDN Recovery Actions.

Iterates through path hops generated by PathSelector, pushing real OpenFlow flow-mod
rules to the Ryu SDN controller via RyuSDNControllerClient.
Features transactional atomic rollbacks if any hop installation fails.
"""

import asyncio
import logging
import time
from dataclasses import dataclass, asdict
from typing import Dict, Any, List, Optional

from backend.controller.sdn_controller import RyuSDNControllerClient, FlowInstallationFailed, ControllerUnavailable

logger = logging.getLogger(__name__)

# Standard SentinelNet Recovery Flow Cookie tag (ASCII 'SENT' = 0x53454E54)
SENTINELNET_RECOVERY_COOKIE = 0x53454E54


@dataclass
class ExecutionResult:
    """Outcome of recovery action execution across switch hops."""
    success: bool
    duration_ms: float
    installed_flows: List[Dict[str, Any]]
    error: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


class ActionExecutor:
    """Executes atomic self-healing mitigation actions on SDN switches."""

    def __init__(self, sdn_controller: Optional[RyuSDNControllerClient] = None):
        self.sdn_controller = sdn_controller or RyuSDNControllerClient()
        logger.info("ActionExecutor initialized with real RyuSDNControllerClient")

    async def execute(self, action: Dict[str, Any]) -> ExecutionResult:
        """Execute a structured recovery action across target switches.

        Args:
            action = {
                "type": "reroute",
                "incident_id": str or int,
                "new_path": Dict from PathSelector (contains "hops"),
                "priority": Optional[int] (defaults to 300 for failover)
            }

        Returns:
            ExecutionResult: {success: bool, duration_ms: float, installed_flows: list, error: str}
        """
        action_type = action.get("type", "reroute")
        incident_id = action.get("incident_id")
        path_data = action.get("new_path", {})
        hops = path_data.get("hops", [])
        priority = int(action.get("priority", 300))

        start_time = time.perf_counter()
        installed_flows: List[Dict[str, Any]] = []

        logger.info(
            "Executing recovery action '%s' for Incident %s (%d switch hops)...",
            action_type, incident_id, len(hops)
        )

        if not hops:
            logger.warning("Recovery action contains no switch hops to configure.")
            return ExecutionResult(
                success=False,
                duration_ms=0.0,
                installed_flows=[],
                error="Action payload has empty hops list"
            )

        # Flow match criteria
        flow_info = action.get("flow") or {}
        flow_src_ip = flow_info.get("src_ip") if isinstance(flow_info, dict) else getattr(flow_info, "src_ip", None)
        flow_dst_ip = flow_info.get("dst_ip") if isinstance(flow_info, dict) else getattr(flow_info, "dst_ip", None)

        # Iterate through hops and push flow entries
        for hop_idx, hop in enumerate(hops):
            dpid = int(hop["dpid"])
            in_port = int(hop["in_port"])
            out_port = int(hop["out_port"])

            # Match on in_port and IPv4 eth_type with SentinelNet recovery cookie
            match_dict = {
                "in_port": in_port,
                "eth_type": 0x0800  # IPv4
            }
            if flow_src_ip:
                match_dict["ipv4_src"] = flow_src_ip
            if flow_dst_ip:
                match_dict["ipv4_dst"] = flow_dst_ip

            flow_rule = {
                "dpid": dpid,
                "priority": priority,
                "cookie": SENTINELNET_RECOVERY_COOKIE,
                "match": match_dict,
                "actions": [
                    {"type": "OUTPUT", "port": out_port}
                ]
            }

            logger.info(
                "Hop %d/%d: Installing flow on DPID %d (in_port %d -> out_port %d, cookie=0x%X)...",
                hop_idx + 1, len(hops), dpid, in_port, out_port, SENTINELNET_RECOVERY_COOKIE
            )

            try:
                # Calls real Ryu REST API + active verification in sdn_controller
                res = await self.sdn_controller.add_flow_entry(flow_rule)
                installed_flows.append(flow_rule)
                logger.debug("Successfully installed flow rule on DPID %d: %s", dpid, res)

            except Exception as exc:
                logger.error(
                    "FAILED to install flow rule on DPID %d (Hop %d): %s. Rolling back installed hops...",
                    dpid, hop_idx + 1, exc
                )

                # ATOMIC ROLLBACK: Remove any flows installed during this failed batch
                for rollback_rule in reversed(installed_flows):
                    try:
                        del_rule = {
                            "dpid": rollback_rule["dpid"],
                            "priority": rollback_rule["priority"],
                            "match": rollback_rule["match"],
                            "cookie": rollback_rule.get("cookie", SENTINELNET_RECOVERY_COOKIE)
                        }
                        await self.sdn_controller.delete_flow_entry(del_rule)
                        logger.info("Atomic rollback: deleted flow from DPID %d", rollback_rule["dpid"])
                    except Exception as rb_exc:
                        logger.critical("Secondary error during atomic rollback on DPID %d: %s", rollback_rule["dpid"], rb_exc)

                duration_ms = round((time.perf_counter() - start_time) * 1000.0, 2)
                return ExecutionResult(
                    success=False,
                    duration_ms=duration_ms,
                    installed_flows=[],
                    error=f"Flow installation failed at hop {hop_idx + 1} (DPID {dpid}): {str(exc)}"
                )

        duration_ms = round((time.perf_counter() - start_time) * 1000.0, 2)
        logger.info(
            "All %d hops successfully installed and verified in %.2fms",
            len(hops), duration_ms
        )

        return ExecutionResult(
            success=True,
            duration_ms=duration_ms,
            installed_flows=installed_flows,
            error=None
        )
